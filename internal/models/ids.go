package models

import (
	"crypto/rand"
	"encoding/hex"
	"sync"
	"time"
)

var (
	uuidMu      sync.Mutex
	uuidLastMs  int64
	uuidCounter uint16 // 12-bit counter that keeps IDs strictly increasing inside one millisecond
)

// NewUUIDv7 returns a time-ordered UUID (RFC 9562 version 7) in its canonical
// 8-4-4-4-12 form, e.g. 0192f6a4-7c3e-7b52-9d1a-4f6e2a8b1c03.
//
// Layout: 48-bit Unix-millisecond timestamp, version 7, a 12-bit counter, then
// 62 random bits. Because the timestamp comes first, IDs sort by creation time
// (good for MongoDB's _id index: inserts append instead of scattering). The
// counter makes IDs generated by this process strictly increasing even within
// the same millisecond, and the 62 random bits make IDs from different
// processes/instances collide with negligible probability (~2^-62 per
// same-millisecond pair).
func NewUUIDv7() string {
	var b [16]byte
	if _, err := rand.Read(b[:]); err != nil {
		panic("models: crypto/rand failed: " + err.Error())
	}

	uuidMu.Lock()
	ms := time.Now().UnixMilli()
	if ms > uuidLastMs {
		uuidLastMs = ms
		// Random start below 0x800 leaves plenty of headroom before overflow.
		uuidCounter = uint16(b[6]&0x07)<<8 | uint16(b[7])
	} else {
		// Same millisecond (or the clock stepped back): keep counting up so the
		// order never goes backwards.
		uuidCounter++
		if uuidCounter > 0x0fff {
			uuidLastMs++
			uuidCounter = 0
		}
	}
	ts, ctr := uuidLastMs, uuidCounter
	uuidMu.Unlock()

	b[0] = byte(ts >> 40)
	b[1] = byte(ts >> 32)
	b[2] = byte(ts >> 24)
	b[3] = byte(ts >> 16)
	b[4] = byte(ts >> 8)
	b[5] = byte(ts)
	b[6] = 0x70 | byte(ctr>>8) // version 7 + counter high bits
	b[7] = byte(ctr)
	b[8] = (b[8] & 0x3f) | 0x80 // RFC 4122 variant

	var out [36]byte
	hex.Encode(out[0:8], b[0:4])
	out[8] = '-'
	hex.Encode(out[9:13], b[4:6])
	out[13] = '-'
	hex.Encode(out[14:18], b[6:8])
	out[18] = '-'
	hex.Encode(out[19:23], b[8:10])
	out[23] = '-'
	hex.Encode(out[24:36], b[10:16])
	return string(out[:])
}
